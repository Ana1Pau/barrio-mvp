-- Barrio MVP: account, merchant onboarding, payment preferences and Pey status.
-- Do not store the CLABE, Pey API key, webhook secret, or other bank credentials here.

create table if not exists public.barrio_neighborhoods (
  id bigint generated by default as identity primary key,
  name text not null,
  city text not null default 'CDMX',
  unique (name, city)
);

create table if not exists public.barrio_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  icon text,
  active boolean not null default true
);

create table if not exists public.barrio_users (
  id uuid primary key default gen_random_uuid(),
  email text unique,
  phone text unique,
  password_hash bytea not null,
  password_salt bytea not null,
  roles text[] not null check (roles <@ array['Comprador','Comercio']::text[] and cardinality(roles) > 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint barrio_users_contact_required check (email is not null or phone is not null)
);

create table if not exists public.barrio_profiles (
  user_id uuid primary key references public.barrio_users(id) on delete cascade,
  display_name text not null,
  biography text,
  neighborhood_id bigint references public.barrio_neighborhoods(id),
  updated_at timestamptz not null default now()
);

create table if not exists public.barrio_merchants (
  id uuid primary key default gen_random_uuid(),
  owner_user_id uuid not null unique references public.barrio_users(id) on delete cascade,
  name text not null,
  description text,
  neighborhood_id bigint references public.barrio_neighborhoods(id),
  show_in_directory boolean not null default true,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.barrio_merchant_categories (
  merchant_id uuid not null references public.barrio_merchants(id) on delete cascade,
  category_id bigint not null references public.barrio_categories(id),
  primary key (merchant_id, category_id)
);

create table if not exists public.barrio_payment_methods (
  code text primary key,
  name text not null,
  description text,
  sort_order smallint not null unique
);

create table if not exists public.barrio_merchant_payment_methods (
  merchant_id uuid not null references public.barrio_merchants(id) on delete cascade,
  method_code text not null references public.barrio_payment_methods(code),
  selected boolean not null default false,
  enabled boolean not null default false,
  configuration_status text not null default 'PENDIENTE'
    check (configuration_status in ('DISPONIBLE','PENDIENTE','REQUIERE_PEY','PROXIMAMENTE')),
  updated_at timestamptz not null default now(),
  primary key (merchant_id, method_code)
);

create table if not exists public.barrio_pey_bank_accounts (
  id uuid primary key default gen_random_uuid(),
  merchant_id uuid not null unique references public.barrio_merchants(id) on delete cascade,
  pey_bank_account_id text not null unique,
  clabe_last4 char(4) not null check (clabe_last4 ~ '^[0-9]{4}$'),
  codi_status text not null check (codi_status in ('PENDING','PROCESSING','ACTIVE','ERROR')),
  created_at timestamptz not null default now(),
  updated_at timestamptz
);

create table if not exists public.barrio_pey_registration_attempts (
  id uuid primary key default gen_random_uuid(),
  merchant_id uuid not null references public.barrio_merchants(id) on delete cascade,
  idempotency_key text not null,
  clabe_last4 char(4) not null check (clabe_last4 ~ '^[0-9]{4}$'),
  state text not null check (state in ('SOLICITANDO','REGISTRADA','INCIERTA')),
  created_at timestamptz not null default now(),
  unique (merchant_id, idempotency_key)
);

