create or replace function public.barrio_register_user(
  p_email text, p_phone text, p_password_hash bytea, p_password_salt bytea,
  p_roles text[], p_display_name text, p_biography text, p_neighborhood_id bigint
) returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_user_id uuid;
begin
  if cardinality(p_roles) < 1 or not (p_roles <@ array['Comprador','Comercio']::text[]) then
    raise exception 'invalid_roles' using errcode = '22023';
  end if;
  insert into public.barrio_users(email, phone, password_hash, password_salt, roles)
  values (nullif(lower(trim(p_email)),''), nullif(trim(p_phone),''), p_password_hash, p_password_salt, p_roles)
  returning id into v_user_id;
  insert into public.barrio_profiles(user_id, display_name, biography, neighborhood_id)
  values (v_user_id, trim(p_display_name), nullif(trim(p_biography),''), p_neighborhood_id);
  return jsonb_build_object('user_id',v_user_id,'roles',p_roles);
end $$;

create or replace function public.barrio_create_merchant(
  p_user_id uuid, p_name text, p_description text, p_neighborhood_id bigint,
  p_category_id bigint, p_show_in_directory boolean
) returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_merchant_id uuid;
begin
  if not exists(select 1 from public.barrio_users where id=p_user_id and active and 'Comercio'=any(roles)) then
    raise exception 'merchant_role_required' using errcode='42501';
  end if;
  insert into public.barrio_merchants(owner_user_id,name,description,neighborhood_id,show_in_directory)
  values(p_user_id,trim(p_name),nullif(trim(p_description),''),p_neighborhood_id,p_show_in_directory)
  returning id into v_merchant_id;
  insert into public.barrio_merchant_categories(merchant_id,category_id) values(v_merchant_id,p_category_id);
  return jsonb_build_object('merchant_id',v_merchant_id);
end $$;

create or replace function public.barrio_save_payment_methods(p_user_id uuid,p_methods jsonb)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_merchant_id uuid; v_result jsonb;
begin
  select id into v_merchant_id from public.barrio_merchants where owner_user_id=p_user_id and active;
  if v_merchant_id is null then raise exception 'merchant_profile_required' using errcode='23503'; end if;
  insert into public.barrio_merchant_payment_methods(merchant_id,method_code,selected,enabled,configuration_status)
  select v_merchant_id, m.code, m.selected,
    (m.code='EFECTIVO' and m.selected),
    case when not m.selected then 'PENDIENTE'
      when m.code='EFECTIVO' then 'DISPONIBLE'
      when m.code='PEY_CODI' then 'REQUIERE_PEY'
      when m.code='NFC' then 'PROXIMAMENTE'
      else 'PENDIENTE' end
  from jsonb_to_recordset(p_methods) as m(code text,selected boolean)
  on conflict(merchant_id,method_code) do update set
    selected=excluded.selected,enabled=excluded.enabled,
    configuration_status=excluded.configuration_status,updated_at=now();
  select coalesce(jsonb_agg(jsonb_build_object('code',pm.code,'name',pm.name,'selected',mp.selected,'enabled',mp.enabled,'configurationStatus',mp.configuration_status) order by pm.sort_order),'[]'::jsonb)
  into v_result from public.barrio_merchant_payment_methods mp
  join public.barrio_payment_methods pm on pm.code=mp.method_code where mp.merchant_id=v_merchant_id;
  return v_result;
end $$;

create or replace function public.barrio_begin_pey_registration(p_user_id uuid,p_key text,p_clabe_last4 char(4))
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_merchant_id uuid; v_account public.barrio_pey_bank_accounts%rowtype; v_attempt public.barrio_pey_registration_attempts%rowtype;
begin
  select id into v_merchant_id from public.barrio_merchants where owner_user_id=p_user_id and active for update;
  if v_merchant_id is null then raise exception 'merchant_profile_required' using errcode='23503'; end if;
  select * into v_account from public.barrio_pey_bank_accounts where merchant_id=v_merchant_id;
  if found then return jsonb_build_object('should_register',false,'bank_account_id',v_account.pey_bank_account_id,'status',v_account.codi_status,'clabe_last4',v_account.clabe_last4); end if;
  select * into v_attempt from public.barrio_pey_registration_attempts
    where merchant_id=v_merchant_id and state in ('SOLICITANDO','INCIERTA') order by created_at desc limit 1;
  if found then return jsonb_build_object('should_register',false,'state',v_attempt.state,'clabe_last4',v_attempt.clabe_last4); end if;
  select * into v_attempt from public.barrio_pey_registration_attempts where merchant_id=v_merchant_id and idempotency_key=p_key;
  if found then
    return jsonb_build_object('should_register',false,'state',v_attempt.state,'clabe_last4',v_attempt.clabe_last4);
  end if;
  if not found then
    insert into public.barrio_pey_registration_attempts(merchant_id,idempotency_key,clabe_last4,state)
    values(v_merchant_id,p_key,p_clabe_last4,'SOLICITANDO') returning * into v_attempt;
  end if;
  return jsonb_build_object('should_register',true,'merchant_id',v_merchant_id,'clabe_last4',v_attempt.clabe_last4);
end $$;

create or replace function public.barrio_finish_pey_registration(
  p_user_id uuid,p_merchant_id uuid,p_key text,p_pey_account_id text,p_clabe_last4 char(4),p_status text
) returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if p_status not in ('PENDING','PROCESSING','ACTIVE','ERROR') then raise exception 'invalid_pey_status' using errcode='22023'; end if;
  if not exists(select 1 from public.barrio_merchants where id=p_merchant_id and owner_user_id=p_user_id) then raise exception 'forbidden' using errcode='42501'; end if;
  insert into public.barrio_pey_bank_accounts(merchant_id,pey_bank_account_id,clabe_last4,codi_status)
  values(p_merchant_id,p_pey_account_id,p_clabe_last4,p_status)
  on conflict(merchant_id) do update set pey_bank_account_id=excluded.pey_bank_account_id,clabe_last4=excluded.clabe_last4,codi_status=excluded.codi_status,updated_at=now();
  update public.barrio_pey_registration_attempts set state='REGISTRADA' where merchant_id=p_merchant_id and idempotency_key=p_key;
  insert into public.barrio_merchant_payment_methods(merchant_id,method_code,selected,enabled,configuration_status)
  values(p_merchant_id,'PEY_CODI',true,p_status='ACTIVE',case when p_status='ACTIVE' then 'DISPONIBLE' else 'PENDIENTE' end)
  on conflict(merchant_id,method_code) do update set selected=true,enabled=(p_status='ACTIVE'),configuration_status=excluded.configuration_status,updated_at=now();
  return jsonb_build_object('bank_account_id',p_pey_account_id,'status',p_status,'clabe_last4',p_clabe_last4);
end $$;

create or replace function public.barrio_mark_pey_attempt_uncertain(p_user_id uuid,p_merchant_id uuid,p_key text)
returns void language plpgsql security definer set search_path = public, pg_temp as $$
begin
  update public.barrio_pey_registration_attempts a set state='INCIERTA'
  where a.merchant_id=p_merchant_id and a.idempotency_key=p_key
    and exists(select 1 from public.barrio_merchants m where m.id=p_merchant_id and m.owner_user_id=p_user_id);
end $$;

